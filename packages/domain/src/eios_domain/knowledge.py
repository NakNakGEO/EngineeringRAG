class DecisionStatus(StrEnum):
    PROPOSED = "proposed"
    ACCEPTED = "accepted"
    REJECTED = "rejected"
    SUPERSEDED = "superseded"


class DecisionCreate(BaseModel):
    model_config = ConfigDict(frozen=True)

    vault: Vault = Vault.PROJECT
    project_id: uuid.UUID | None = None
    question: str = Field(min_length=1, max_length=2000)
    alternatives: list[dict[str, Any]] = Field(default_factory=list)
    selected: str = Field(default="", max_length=2000)
    rationale: str = Field(default="", max_length=20_000)
    evidence_ids: list[uuid.UUID] = Field(default_factory=list)
    decider: str = Field(min_length=1, max_length=200)
    reviewers: list[str] = Field(default_factory=list)
    status: DecisionStatus = DecisionStatus.PROPOSED

    @model_validator(mode="after")
    def _invariants(self) -> Self:
        if self.vault is Vault.EPHEMERAL:
            raise ValueError("decisions are durable and cannot live in the ephemeral vault")
        check_vault_invariants(self.vault, project_id=self.project_id, expires_at=None)
        return self


