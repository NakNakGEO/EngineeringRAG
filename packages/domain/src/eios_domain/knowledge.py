class Trust(StrEnum):
    RAW = "RAW"
    OBSERVED = "OBSERVED"
    DERIVED = "DERIVED"
    VERIFIED = "VERIFIED"
    APPROVED = "APPROVED"

    @property
    def rank(self) -> int:
        return list(Trust).index(self)

    def __lt__(self, other: object) -> bool:
        return isinstance(other, Trust) and self.rank < other.rank

    def __le__(self, other: object) -> bool:
        return isinstance(other, Trust) and self.rank <= other.rank


class Health(StrEnum):
    CURRENT = "CURRENT"
    UNVERIFIED = "UNVERIFIED"
    STALE = "STALE"
    CONTRADICTED = "CONTRADICTED"
    SUPERSEDED = "SUPERSEDED"
    HISTORICAL = "HISTORICAL"
    QUARANTINED = "QUARANTINED"


class SourceKind(StrEnum):
    MANUAL = "manual"  # typed by a human
    TOOL = "tool"  # output of a tool/adapter
    LLM = "llm"  # generated by a model
    CODE = "code"  # extracted by a deterministic parser from source
    RESEARCH = "research"  # public/web research
    IMPORT = "import"  # imported package


# Highest trust a record may be *created* with, by source. Anything higher has to be earned
# through the evidence pipeline and verification (Phase 9). Raw tool output and LLM assertions
# can never be created as VERIFIED/APPROVED.
TRUST_CEILING: dict[SourceKind, Trust] = {
    SourceKind.MANUAL: Trust.APPROVED,
    SourceKind.CODE: Trust.DERIVED,
    SourceKind.IMPORT: Trust.DERIVED,
    SourceKind.TOOL: Trust.OBSERVED,
    SourceKind.RESEARCH: Trust.OBSERVED,
    SourceKind.LLM: Trust.OBSERVED,
}
PIPELINE_CEILING = Trust.DERIVED  # knowledge created from an evidence-backed finding


class TrustViolationError(ValueError):
    """A trust level was claimed that the source or pipeline does not justify."""


class ProvenanceInput(BaseModel):
    model_config = ConfigDict(frozen=True)

    source: str = Field(min_length=1, max_length=500, description="file, URL, tool id, ...")
    source_version: str | None = Field(default=None, max_length=200, description="e.g. commit")
    actor: str = Field(min_length=1, max_length=200, description="model, tool or human")
    evidence_id: uuid.UUID | None = None
    evidence_hash: str | None = Field(default=None, max_length=128)
    notes: str = ""


class KnowledgeItemCreate(BaseModel):
    model_config = ConfigDict(frozen=True)

    vault: Vault
    project_id: uuid.UUID | None = None
    kind: str = Field(default="note", min_length=1, max_length=60)
    title: str = Field(min_length=1, max_length=300)
    content: str = Field(min_length=1, max_length=200_000)
    tags: list[str] = Field(default_factory=list, max_length=50)
    trust: Trust = Trust.RAW
    health: Health = Health.UNVERIFIED
    confidence: float = Field(default=0.5, ge=0, le=1)
    source_kind: SourceKind
    created_by: str = Field(min_length=1, max_length=200)
    expires_at: datetime | None = None
    subject_key: str | None = Field(default=None, max_length=300)
    limitations: str = ""
    version_ref: str | None = Field(default=None, max_length=200)
    metadata: dict[str, Any] = Field(default_factory=dict)
    provenance: list[ProvenanceInput] = Field(default_factory=list)
    from_pipeline: bool = Field(
        default=False, description="created from an evidence-backed finding (raises the ceiling)"
    )

    @model_validator(mode="after")
    def _invariants(self) -> Self:
        check_vault_invariants(self.vault, project_id=self.project_id, expires_at=self.expires_at)
        ceiling = (
            PIPELINE_CEILING
            if self.from_pipeline and self.source_kind is not SourceKind.MANUAL
            else TRUST_CEILING[self.source_kind]
        )
        if not self.trust <= ceiling:
            raise TrustViolationError(
                f"{self.source_kind.value} knowledge cannot be created with trust "
                f"{self.trust.value} (ceiling {ceiling.value})"
            )
        if self.source_kind is not SourceKind.MANUAL and not self.provenance:
            raise TrustViolationError("non-manual knowledge requires provenance")
        if self.health is Health.CURRENT and self.trust <= Trust.RAW:
            raise TrustViolationError("RAW knowledge cannot be marked CURRENT")
        return self


